def all_tickers(market: str) -> list[str]:
    """全シナリオに登場する指定市場のティッカー一覧（重複除去・順序維持）"""
    seen: list[str] = []
    for g in SCENARIOS:
        for opt in g["options"]:
            for st in opt["stocks"].get(market, []):
                if st["ticker"] not in seen:
                    seen.append(st["ticker"])
    return seen


def build_payload(quotes: dict[str, dict]) -> dict:
    """
    SCENARIOS に日次データ（quotes: {ticker: {close, chg, spark}}）を合成して
    フロントエンド用の dict を返す。データが無い銘柄はリストに残し、価格欄は None。
    """
    groups = []
    for g in SCENARIOS:
        options = []
        for opt in g["options"]:
            stocks = {}
            for market, lst in opt["stocks"].items():
                rows = []
                for st in lst:
                    q = quotes.get(st["ticker"], {})
                    rows.append({**st,
                                 "close": q.get("close"),
                                 "chg": q.get("chg"),
                                 "spark": q.get("spark")})
                stocks[market] = rows
            options.append({"id": opt["id"], "label": opt["label"],
                            "summary": opt["summary"], "stocks": stocks})
        groups.append({"id": g["id"], "icon": g["icon"], "label": g["label"],
                       "question": g["question"], "options": options})
    return {"as_of": EDITORIAL_DATE, "groups": groups}
